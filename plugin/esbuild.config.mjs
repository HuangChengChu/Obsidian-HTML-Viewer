import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { mkdirSync, copyFileSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const prod = process.argv[2] === "production";
const outdir = resolve(__dirname, "../dist/plugin");
mkdirSync(outdir, { recursive: true });

/**
 * 把 templates/src/runtime.js 作为**文本资源**打进插件。
 *
 * 单一真源：runtime 只有这一份，模板构建和插件注入都读它。
 * 注入到 HTML 时要原样放进 <script> 里，所以用 text loader 而不是当模块打包。
 */
const runtimeTextPlugin = {
  name: "runtime-text",
  setup(build) {
    build.onResolve({ filter: /^runtime-source$/ }, () => ({
      path: "runtime-source",
      namespace: "runtime-text",
    }));
    build.onLoad({ filter: /.*/, namespace: "runtime-text" }, () => ({
      contents: readFileSync(resolve(__dirname, "../templates/src/runtime.js"), "utf8"),
      loader: "text",
    }));
  },
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin source folder
*/
`;

const ctx = await esbuild.context({
  banner: { js: banner },
  entryPoints: [resolve(__dirname, "src/main.ts")],
  bundle: true,
  plugins: [runtimeTextPlugin],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: resolve(outdir, "main.js"),
});

if (prod) {
  await ctx.rebuild();
  await ctx.dispose();
  copyFileSync(resolve(__dirname, "manifest.json"), resolve(outdir, "manifest.json"));
  copyFileSync(resolve(__dirname, "styles.css"), resolve(outdir, "styles.css"));
  console.log("[build] dist/plugin ready");
} else {
  await ctx.watch();
  console.log("[build] watching...");
}
